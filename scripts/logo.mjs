#!/usr/bin/env node
// The GitFlux mark: three snapshots joined by their history. One white (where you are), two green.
// Writes the SVG files and prints the inner markup the page and the video reuse.
//   node scripts/logo.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const T = { x: 15.6, y: 8.7, r: 2.6, w: 1.9 };   // top: white ring
const L = { x: 8.5, y: 18.9, r: 2.7, w: 2.2 };    // left: green ring
const R = { x: 23.3, y: 21.6, r: 3.1, w: 2.4 };   // right: green ring, a little bigger
const GREEN = '#3DDC6B', GREEN2 = '#2BC46F', MINT = '#8EF0AE', INK = '#0B0D10';

/** A line between two rings that stops at each ring's outer edge. */
function edge(a, b) {
  const dx = b.x - a.x, dy = b.y - a.y, len = Math.hypot(dx, dy), ux = dx / len, uy = dy / len;
  // end on each ring's centre line, so the ring drawn on top closes the joint with no gap
  const ga = a.r, gb = b.r;
  const f = n => +n.toFixed(2);
  return { x1: f(a.x + ux * ga), y1: f(a.y + uy * ga), x2: f(b.x - ux * gb), y2: f(b.y - uy * gb) };
}
const e1 = edge(T, L), e2 = edge(T, R), e3 = edge(L, R);
const grad = (id, e, stops) => `<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${e.x1}" y1="${e.y1}" x2="${e.x2}" y2="${e.y2}">${stops.map(([o, c, a]) => `<stop offset="${o}" stop-color="${c}" stop-opacity="${a}"/>`).join('')}</linearGradient>`;
const line = (e, id) => `<line x1="${e.x1}" y1="${e.y1}" x2="${e.x2}" y2="${e.y2}" stroke="url(#${id})" stroke-width="2.1" stroke-linecap="round"/>`;
const ring = (n, c) => `<circle cx="${n.x}" cy="${n.y}" r="${n.r}" fill="none" stroke="${c}" stroke-width="${n.w}"/>`;

/** The mark's markup; `p` prefixes gradient ids so several copies can share a page. */
const mark = (p = 'gf') => [
  `<rect width="32" height="32" rx="9" fill="${INK}"/>`,
  `<defs>${grad(`${p}a`, e1, [[0, '#FFFFFF', 1], [0.5, MINT, 1], [1, GREEN, 1]])}${grad(`${p}b`, e2, [[0, '#FFFFFF', 1], [0.5, MINT, 1], [1, GREEN2, 1]])}${grad(`${p}c`, e3, [[0, GREEN, 1], [0.5, '#34D26D', 1], [1, GREEN2, 1]])}</defs>`,
  line(e1, `${p}a`), line(e2, `${p}b`), line(e3, `${p}c`),
  ring(T, '#FFFFFF'), ring(L, GREEN), ring(R, GREEN2),
].join('');

const svg = size => `<svg xmlns="http://www.w3.org/2000/svg"${size ? ` width="${size}" height="${size}"` : ''} viewBox="0 0 32 32">${mark()}</svg>\n`;

writeFileSync(path.join(root, 'packages/ui/public/favicon.svg'), svg());
writeFileSync(path.join(root, 'docs/images/logo.svg'), svg(88));
const ts = `// Generated by scripts/logo.mjs: edit that file, not this one.
/** The GitFlux mark's SVG markup. Gradient ids start with "gf"; replace that prefix to place several on one page. */
export const LOGO_MARK = '${mark()}';
`;
writeFileSync(path.join(root, 'packages/ui/src/logo-mark.ts'), ts);
writeFileSync(path.join(root, 'video/src/explainer/logo-mark.ts'), ts);
console.log('logo written: favicon, docs/images/logo.svg, page and video marks');
